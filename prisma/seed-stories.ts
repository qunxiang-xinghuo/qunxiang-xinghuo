async function main() {
  console.log("[Seed] 开始插入5个太仓解密故事...");

  for (const story of stories) {
    const { roles, ...storyData } = story;
    const created = await db.story.create({
      data: {
        ...storyData,
        roles: {
          create: roles,
        },
      },
    });
    console.log(`[Seed] 已创建故事: ${created.title} (${created.id})`);
  }

  console.log("[Seed] 完成！");
}

main()
  .catch((e) => {
    console.error("[Seed] 错误:", e);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
